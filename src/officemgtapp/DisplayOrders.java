    private void jbDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbDeleteActionPerformed
                                            
        String Sql="delete from Orders where OrderID=?";
        try{
            pst=conn.prepareStatement(Sql);
            pst.setInt(1,Integer.parseInt(this.tfOrderId.getText()));
            int i = pst.executeUpdate();
            if(i>0){
                JOptionPane.showMessageDialog(null, "Order Information has been deleted successfully");
                this.dispose();
                new DisplayOrders().setVisible(true);
            }
            else{
                 JOptionPane.showMessageDialog(null,"Data has not been deleted successfully");
            }
                    
        }catch(HeadlessException | SQLException e){
            JOptionPane.showMessageDialog(null, e);
        }        // TODO add your handling code here:
    }//GEN-LAST:event_jbDeleteActionPerformed

