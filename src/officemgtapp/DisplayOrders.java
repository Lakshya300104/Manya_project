    private void jbUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbUpdateActionPerformed
                                        
         String Sql="update Orders set Product=?, CustomerID=?, Thickness=?, FinalPrice=?, Priceperunit=?, Manufacturer=?, Quantity=? where OrderID=?";
        try{
            
            pst=conn.prepareStatement(Sql);
           
            pst.setString(1,this.tfQuantity.getText());
            pst.setString(2,this.tfOrderId.getText());
            pst.setString(3,this.tfFinalprice.getText());
            pst.setString(4,this.tfProduct.getText());
            pst.setString(5,this.tfThickness.getText());
            pst.setString(6,this.tfPriceperunit.getText());
            pst.setString(7,this.tfCustomerID.getText());
            pst.setString(8,this.tfManufacturer.getText());
           
            int i = pst.executeUpdate();
            if(i>0){
          
                JOptionPane.showMessageDialog(null, "Data has been updated");
                this.dispose();
                new DisplayOrders().setVisible(true);
            }
            else{
                 JOptionPane.showMessageDialog(null,"Data is not saved");
            }
        }
        catch(HeadlessException | SQLException e){
            JOptionPane.showMessageDialog(null, e);
        }        // TODO add your handling code here:
    }//GEN-LAST:event_jbUpdateActionPerformed

