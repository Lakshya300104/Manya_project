    private void jbUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbUpdateActionPerformed

        String Sql= "update addcustomers set CustomerName=?, EmailID=?, City=?, GST=?, PAN=? where CustomerID=?";
        try{

            pst=conn.prepareStatement(Sql);
            pst.setString(1,this.tfCustomerID.getText());
            pst.setString(2,this.tfCustomerName.getText());
            pst.setString(3,this.tfEmailID.getText());
            pst.setString(4,this.tfCity.getText());
            pst.setString(5,this.tfGST.getText());
            pst.setString(6,this.tfPAN.getText());


            int i = pst.executeUpdate();
            if(i>0){

                JOptionPane.showMessageDialog(null, "Customer information has been changed");
                this.dispose();
                new DisplayOrders().setVisible(true);
            }
            else{
                JOptionPane.showMessageDialog(null,"Data is not saved");
            }
        }
        catch(HeadlessException | SQLException e){
            JOptionPane.showMessageDialog(null, e);
        }        // TODO add your handling code here:
    }//GEN-LAST:event_jbUpdateActionPerformed

