    private void bAddCompanyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bAddCompanyActionPerformed
        String Sql="insert into addinventory values (?,?,?,?,?)";
        try{
            pst = conn.prepareStatement(Sql);
            pst.setString(1,this.tfProduct.getText());
            pst.setString(2,this.tfManufacturer.getText());
            pst.setString(3,this.tfStockAmount.getText());
            pst.setString(4,this.tfThickness.getText());
            pst.setString(5,this.tfGrade.getText());

            int i = pst.executeUpdate();
            if(i>0){

                JOptionPane.showMessageDialog(null, " Inventory Added");
                new AddInventory().setVisible(true);
                this.dispose();
            }
            else{
                JOptionPane.showMessageDialog(null,"Data is not saved");
            }
        }
        catch(HeadlessException | SQLException e){
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_bAddCompanyActionPerformed

