    private String validateCustomer() {
        String id = tfCustomerID.getText().trim();
        String name = tfCustomerName.getText().trim();
        String email = tfEmail.getText().trim();
        String city = tfCity.getText().trim();
        String gst = tfGST.getText().trim().toUpperCase();
        String pan = tfPAN.getText().trim().toUpperCase();
 
        StringBuilder missing = new StringBuilder();
        if (id.isEmpty())    missing.append("\n- Customer ID");
          if (name.isEmpty())  missing.append("\n- Customer Name");
        if (email.isEmpty()) missing.append("\n- Email ID");
        if (city.isEmpty())  missing.append("\n- City");
        if (gst.isEmpty())   missing.append("\n- GST No.");
        if (pan.isEmpty())   missing.append("\n- PAN No.");
        if (missing.length() > 0)
            return "Please fill in:" + missing;
 
        if (!id.matches("[0-9]+"))
            return "Customer ID must be a whole number";
        if (!email.matches("^[\\w.+-]+@[\\w-]+(\\.[\\w-]+)+$"))
            return "Enter a valid email address";
        if (!gst.matches("^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$"))
            return "GST No. must be 15 characters, e.g. 27ABCDE1234F1Z5";
        if (!pan.matches("^[A-Z]{5}[0-9]{4}[A-Z]$"))
            return "PAN No. must be 10 characters, e.g. ABCDE1234F";
        return "";
    }

