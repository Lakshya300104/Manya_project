    private void bAddCustomerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bAddCustomerActionPerformed
        String Sql="insert into addcustomers values (?,?,?,?,?,?)";
        try{
            pst = conn.prepareStatement(Sql);
            pst.setString(1,this.tfCustomerID.getText());
            pst.setString(2,this.tfCustomerName.getText());
            pst.setString(3,this.tfEmail.getText());
            pst.setString(4,this.tfCity.getText());
            pst.setString(5,this.tfGST.getText().toUpperCase());
            pst.setString(6,this.tfPAN.getText().toUpperCase());

            int i = pst.executeUpdate();
            if(i>0){

                JOptionPane.showMessageDialog(null, " Customer Added");
                new AddCustomer().setVisible(true);
                this.dispose();
            }
            else{
                JOptionPane.showMessageDialog(null,"Data is not saved");
            }
        }
        catch(HeadlessException | SQLException e){
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_bAddCustomerActionPerformed

