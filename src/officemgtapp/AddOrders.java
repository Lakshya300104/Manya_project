    private void bAddOrderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bAddOrderActionPerformed
        String Sql="insert into Orders values (?,?,?,?,?,?,?,?,?,?,?)";
        try{
             String d1=((JTextField)jDcExpected.getDateEditor().getUiComponent()).getText();
             String d2=((JTextField)jDcPayment.getDateEditor().getUiComponent()).getText();
             String d3=((JTextField)jDcCurrent.getDateEditor().getUiComponent()).getText();
            pst = conn.prepareStatement(Sql);
            pst.setString(1,this.tfOrderID.getText());
            pst.setString(2,this.tfProduct.getText());
            pst.setString(3,this.tfThickness.getText());
            pst.setString(4,this.tfCustomerID.getText());
            pst.setString(5,this.tfFinalPrice.getText());
            pst.setString(6,this.tfPriceperunit.getText());
            pst.setString(7,this.tfManufacturer.getText());
            pst.setString(8,this.tfQuantity.getText());
            pst.setString(9,d1);
            pst.setString(10,d2);
            pst.setString(11,d3);           
                    
            int i = pst.executeUpdate();
            if(i>0){

                JOptionPane.showMessageDialog(null, "Order succesfully Added");
                new AddOrders().setVisible(true);
                this.dispose();
            }
            else{
                JOptionPane.showMessageDialog(null,"Data is not saved");
            }
        }
        catch(HeadlessException | SQLException e){
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_bAddOrderActionPerformed

